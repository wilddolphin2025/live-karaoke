#!/bin/sh
# Generate ParakeetKaraoke.xcodeproj with xcodegen.
# Optional (private, not needed for forks): if the gitignored Local.xcconfig sets LK_PREMIUM = 1 and
# LK_PREMIUM_PATH = <path to the LiveKaraokePremium package, relative to ios/>, the package and the
# PREMIUM compile flag are added via a generated, gitignored project.premium.yml.
set -e
cd "$(dirname "$0")/.."
val() { [ -f Local.xcconfig ] && sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*\([^[:space:]]*\).*/\1/p" Local.xcconfig | tail -1; }
if [ "$(val LK_PREMIUM)" = "1" ]; then
  P="$(val LK_PREMIUM_PATH)"
  [ -f "$P/Package.swift" ] || { echo "LK_PREMIUM=1 but no package at LK_PREMIUM_PATH='$P'" >&2; exit 1; }
  cat > project.premium.yml <<YML
# Generated by scripts/generate.sh — do not commit.
include: [project.yml]
packages:
  LiveKaraokePremium:
    path: $P
targets:
  ParakeetKaraoke:
    dependencies:
      - package: LiveKaraokePremium
    settings:
      base:
        SWIFT_ACTIVE_COMPILATION_CONDITIONS: \$(inherited) PREMIUM
  ParakeetKaraokeUITests:
    sources: [ParakeetKaraokeUITests, $P/UITests]
YML
  echo "Premium build (package at $P)"
  xcodegen generate --spec project.premium.yml --project .
else
  rm -f project.premium.yml
  xcodegen generate --spec project.yml
fi
